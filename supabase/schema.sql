-- MedRemind — Supabase schema
--
-- Run this whole file once in the Supabase dashboard:
--   SQL Editor -> New query -> paste -> Run
--
-- Only two things in the app use Supabase:
--   * authentication  -> handled by Supabase Auth itself, no tables needed
--   * medicine search -> public.medicine_catalog below
--
-- Medicines, stock, schedules, dose history and the profile are stored on the
-- phone (see js/store.js), so they never touch this database.

-- ---------------------------------------------------------------------------
-- Medicine catalog (read-only reference list used by the search box)
-- ---------------------------------------------------------------------------

create table if not exists public.medicine_catalog (
    id bigint generated by default as identity primary key,
    name text not null,
    generic_name text,
    strength text,
    form text,
    manufacturer text,
    instructions text,
    created_at timestamptz not null default now()
);

create index if not exists medicine_catalog_name_idx on public.medicine_catalog (lower(name));
create index if not exists medicine_catalog_generic_idx on public.medicine_catalog (lower(generic_name));

-- Everyone with the anon key may search the catalog; nobody may write to it
-- from the app (add rows here in the dashboard instead).
alter table public.medicine_catalog enable row level security;

drop policy if exists "medicine_catalog_read" on public.medicine_catalog;
create policy "medicine_catalog_read"
    on public.medicine_catalog
    for select
    to anon, authenticated
    using (true);

